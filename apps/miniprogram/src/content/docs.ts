/** 列表项：开头可以有一段加粗的词（草稿里的 **词**），text 是紧跟在后面的原文，包括冒号。 */
export type DocListItem = string | { term: string; text: string };

export type DocBlock =
  | { kind: "h"; text: string }
  /** 段落；text 里的换行照原样分行。 */
  | { kind: "p"; text: string }
  /** 固定文案 A 这类要突出的整段引文。 */
  | { kind: "quote"; text: string }
  | { kind: "ul"; items: DocListItem[] }
  | { kind: "ol"; items: DocListItem[] };

export interface Doc {
  title: string;
  version: string;
  /** 定稿前为 true，页面在版本号旁写“草稿，待客户确认”。 */
  draft: boolean;
  /** 草稿开头的表格：版本、生效日期、运营主体、联系方式。 */
  facts?: [string, string][];
  blocks: DocBlock[];
}

/** 文档页的 name 参数。写进页面路径，上线后不改。 */
export type DocName = "about" | "agreement" | "privacy";

/** 按 name 参数取文档；不认识的 name（比如手改了路径）返回 null。 */
export function findDoc(name: string | undefined): Doc | null {
  const key = (Object.keys(DOCS) as DocName[]).find((k) => k === name);
  return key ? DOCS[key] : null;
}

